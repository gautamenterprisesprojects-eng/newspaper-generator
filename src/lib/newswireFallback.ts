const backfillDesignChrome = (story: NewswireStory, seedIndex: number): NewswireStory => {
  const category = String(story.category);
  const seedKey = `${story.id}-${seedIndex}`;
  // ── Deliberately do NOT auto-add kicker or strap ribbons here.
  // Earlier iteration backfilled "खेल" / "भास्कर स्पोर्ट्स" on every story;
  // it created visual noise, competed with the headline for space, and the
  // pull-quote/fact-box boxes then overlapped body text because the compose
  // engine doesn't currently flow body around them cleanly. Keep those fields
  // opt-in (only present when the source data explicitly sets them) and only
  // backfill the low-risk fields: byline, place, photo credit, image URL.
  const bylineName = story.bylineName ?? pickFromPool(BYLINE_POOL, seedKey);
  const place = story.place ?? pickFromPool(PLACE_POOL, seedKey, 1);
  const photoCredit = story.photoCredit ?? pickFromPool(PHOTO_CREDIT_POOL, seedKey, 2);
  const imageUrl = story.imageUrl || DEFAULT_IMAGE_BY_CATEGORY[category] || "";

  return {
    ...story,
    imageUrl,
    place,
    bylineName,
    photoCredit,
  };
};


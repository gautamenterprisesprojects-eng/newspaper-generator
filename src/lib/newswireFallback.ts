const BRIEF_VARIANT_KICKERS = ["शॉर्ट न्यूज़", "बड़ी खबरें", "अपडेट", "IN BRIEF"];

const buildBriefVariant = (baseStory: NewswireStory, variantIndex: number): NewswireStory => {
  const seedKey = `${baseStory.id}-brief-${variantIndex}`;
  const seedNum = hashString(seedKey);
  const category = String(baseStory.category);
  // Generate a distinct short brief so the box has real content, not a byte-for-byte duplicate.
  // We reword the headline as an "update" and take only the first sentence of the body.
  const firstSentence = baseStory.body.split(/[।.!?]/)[0]?.trim() || baseStory.headline;
  const briefBody = `${firstSentence}। ${baseStory.summary[variantIndex % Math.max(1, baseStory.summary.length)] ?? ""}`;
  return {
    ...baseStory,
    id: `${baseStory.id}-brief-${variantIndex}`,
    headline: baseStory.summary[variantIndex % Math.max(1, baseStory.summary.length)] ?? baseStory.headline,
    subheadline: firstSentence,
    body: briefBody,
    shortBody: briefBody,
    mediumBody: briefBody,
    longBody: briefBody,
    summary: [firstSentence],
    imageUrl: "",
    caption: "",
    imageCaption: "",
    kicker: BRIEF_VARIANT_KICKERS[seedNum % BRIEF_VARIANT_KICKERS.length],
    strap: DEFAULT_STRAP_BY_CATEGORY[category] ?? baseStory.strap,
    factBoxRows: undefined,
    factBoxHeading: undefined,
    pullQuoteText: undefined,
    pullQuoteAttribution: undefined,
  };
};

/**
 * Returns `limit` unique fallback stories for the given category.
 *
 * When the pool exceeds `limit`, we return the first `limit` stories. When
 * `limit` exceeds the pool, we borrow from other categories first (so a page
 * requesting 12 Sports stories doesn't repeat the same 5), then — as a final
 * fallback — synthesize distinct "brief" variants from the pool (short
 * summary-only boxes with a different headline). Under NO circumstances do we
 * return byte-for-byte duplicates with only an ID suffix changed within one
 * call — that was the bug causing the same headline+body+photo to appear
 * twice on one generated page.
 *
 * Deliberately deterministic for a given (category, limit), though — same
 * input, same output every time, so a document regenerates identically.
 * That determinism is exactly what breaks a *multi-page* batch edition: two
 * pages whose own category pool is thin both borrow/synthesize from the same
 * fixed order and land on the same content. `excludeIds` (ids already used
 * elsewhere in this edition) lets a caller ask this function to keep
 * digging — borrow from the next category, synthesize the next variant —
 * instead of handing back the same fixed early candidates for every page to
 * fight over.
 */
export const getFallbackNewswireStories = (
  category: string,
  limit = 5,
  excludeIds?: Set<string>,
): NewswireStory[] => {
  const primaryPool = FALLBACK_NEWSWIRE_STORIES[category] ?? FALLBACK_NEWSWIRE_STORIES.Sports ?? [];
  const rawList: NewswireStory[] = [];
  const seenHeadlines = new Set<string>();

  const pushUnique = (story: NewswireStory) => {
    if (excludeIds?.has(story.id)) return;
    const key = story.headline.trim();
    if (seenHeadlines.has(key)) return;
    seenHeadlines.add(key);
    rawList.push(story);
  };

  // Step 1: primary pool
  for (const story of primaryPool) {
    if (rawList.length >= limit) break;
    pushUnique(story);
  }

  // Step 2: borrow from other categories (labelled with original category).
  // The borrowed story keeps its original id on purpose — it's the same
  // underlying content regardless of which page's category it's relabeled
  // for, so excludeIds correctly recognizes "already used" even across a
  // category relabel, rather than treating a recycled article as fresh.
  if (rawList.length < limit) {
    for (const otherCategory of Object.keys(FALLBACK_NEWSWIRE_STORIES)) {
      if (otherCategory === category) continue;
      for (const story of FALLBACK_NEWSWIRE_STORIES[otherCategory]) {
        if (rawList.length >= limit) break;
        pushUnique({ ...story, category });
      }
      if (rawList.length >= limit) break;
    }
  }

  // Step 3: synthesize distinct brief variants. Once excludeIds is thinning
  // things out, widen the source beyond just this category's own primary
  // pool (all categories combined) and raise the search ceiling accordingly
  // — otherwise a heavily-exhausted edition runs out of fresh variants to
  // try long before it runs out of legitimate ones to find.
  if (rawList.length < limit) {
    const variantSourcePool = primaryPool.length > 0 ? primaryPool : Object.values(FALLBACK_NEWSWIRE_STORIES).flat();
    if (variantSourcePool.length > 0) {
      let variantIndex = 0;
      const maxAttempts = Math.max(limit * 4, 64);
      while (rawList.length < limit && variantIndex < maxAttempts) {
        const base = variantSourcePool[variantIndex % variantSourcePool.length];
        const brief = buildBriefVariant(base, variantIndex);
        pushUnique(brief);
        variantIndex += 1;
      }
    }
  }

  return rawList.map((story, index) => enrichStoryWordCount(story, index));
};
